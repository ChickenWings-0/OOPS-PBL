// Person.h
// Base class for Student and Teacher.
// Holds what every person in the system has: an internal ID and a name.

#ifndef PERSON_H
#define PERSON_H

#include <string>

class Person {
protected:
    int id;              // internal ID, generated by the program
    std::string name;    // protected, so derived classes can use it directly

public:
    Person();
    Person(int personId, const std::string& personName);
    virtual ~Person();   // virtual: standard for a base class

    int getId() const;
    std::string getName() const;
    void setName(const std::string& newName);

    // Virtual: Student and Teacher each provide their own version.
    virtual void display() const;
};

#endif
